#!/usr/bin/env node
// Combines the hand-written article files in data/topics/*.json into data/topics.json.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const root = new URL('..', import.meta.url).pathname;
const order = ['fundamentals', 'diagnosis', 'nutrition', 'lifestyle', 'lifestages', 'toxicology', 'research'];
const files = readdirSync(root + 'data/topics').filter((f) => f.endsWith('.json'));
const cats = files.map((f) => JSON.parse(readFileSync(root + 'data/topics/' + f, 'utf8'))).sort((a, b) => order.indexOf(a.category) - order.indexOf(b.category));
const items = cats.flatMap((c) => c.items.map((x) => ({ ...x, category: c.category, categoryLabel: c.label, status: x.status || 'editorial' })));
writeFileSync(root + 'data/topics.json', JSON.stringify({ schema: 'topic', version: 1, note: 'Generated by tools/build-topics.mjs from data/topics/*.json; edit those files.', categories: cats.map((c) => ({ id: c.category, label: c.label })), count: items.length, items }, null, 1) + '\n');
console.log(`topics: ${items.length} in ${cats.length} categories`);
